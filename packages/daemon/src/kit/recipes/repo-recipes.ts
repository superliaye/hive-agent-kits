// Repo-specific Recipes (ADR-0034): each covers one Tile's repository, which
// installs only through its own commands. Recognition checks the files those
// commands rely on. The projection is a bundle pointer named after the Tile,
// carrying no commands, plus the repository tree when the commands run in it.

import type { DeployTarget } from "@hive/contract";
import { Effect } from "effect";
import { stringify as yamlStringify } from "yaml";
import type { TreePath } from "../acquisition/snapshot.ts";
import {
  bundlePointer,
  type CapabilityName,
  CHECKOUT_ROOT,
  type GeneratedFile,
} from "./projection.ts";
import {
  type Match,
  miss,
  pluginPointers,
  type RepoInstaller,
  type RepoRecipe,
  readMarketplaces,
} from "./recipe.ts";

function tileBundlePointer(
  tile: CapabilityName,
  description: string,
  targets: readonly DeployTarget[],
  commit: string,
): GeneratedFile {
  const frontmatter = yamlStringify({
    description,
    installer: { kind: "tile", tile },
    targets,
    source_commit: commit,
  });
  return { to: bundlePointer(tile), text: `---\n${frontmatter}---\n` };
}

const GSTACK = "gstack" as CapabilityName;

const gstackHost = (host: DeployTarget, home: "claude" | "codex") =>
  ({
    install: {
      requires: ["bun"],
      commands: [{ argv: ["./setup", "--host", host, "-q"], cwd: "checkout" }],
    },
    uninstall: {
      scope: "all-targets",
      requires: [],
      commands: [{ argv: ["./bin/gstack-uninstall", "--force"], cwd: "checkout" }],
    },
    proofs: [
      { home, path: "skills/gstack/SKILL.md" },
      { home, path: "skills/gstack-upgrade/SKILL.md" },
    ],
  }) as const;

// gstack's README installs Claude from a clone at ~/.claude/skills/gstack, and
// its setup warns when a Codex-only install runs from there.
const GSTACK_INSTALLER: RepoInstaller = {
  checkout: { at: { claude: { home: "claude", path: "skills/gstack" } } },
  targets: { claude: gstackHost("claude", "claude"), codex: gstackHost("codex", "codex") },
};

export const gstackRecipe: RepoRecipe = {
  id: "gstack-setup",
  label: "gstack setup",
  unit: "whole",
  trust: "repo",
  installer: GSTACK_INSTALLER,
  recognize: (tree) => {
    const { remote } = tree;
    if (!remote) return Effect.succeed(miss("not a whole git repository"));
    if (tree.kind("setup" as TreePath) !== "file") return Effect.succeed(miss("no setup script"));
    if (tree.kind("bin/gstack-uninstall" as TreePath) !== "file") {
      return Effect.succeed(miss("no bin/gstack-uninstall"));
    }
    return Effect.succeed({
      _tag: "Match",
      projection: {
        copies: [{ from: "" as TreePath, to: CHECKOUT_ROOT, exclude: "none" }],
        writes: [
          tileBundlePointer(
            GSTACK,
            "gstack's skills, generated by its own setup for each CLI.",
            ["claude", "codex"],
            remote.commit,
          ),
        ],
      },
    } satisfies Match);
  },
};

const UI_UX_PRO_MAX = "ui-ux-pro-max" as CapabilityName;

// The skills `uipro init --ai codex --global` writes to ~/.agents/skills.
const UIPRO_CODEX_SKILLS = [
  "banner-design",
  "brand",
  "design",
  "design-system",
  "slides",
  "ui-styling",
  "ui-ux-pro-max",
];

const uipro = (command: "init" | "uninstall") =>
  ["npx", "-y", "ui-ux-pro-max-cli", command, "--ai", "codex", "--global"] as const;

// Codex installs through the repository's uipro CLI; Claude Code installs the
// repository's own plugin. `uipro uninstall` asks y/N and has no --yes flag.
const UI_UX_PRO_MAX_INSTALLER: RepoInstaller = {
  checkout: null,
  targets: {
    codex: {
      install: { requires: ["npx"], commands: [{ argv: uipro("init"), cwd: null }] },
      uninstall: {
        scope: "target",
        requires: ["npx"],
        commands: [{ argv: uipro("uninstall"), cwd: null, stdin: "y\n" }],
      },
      proofs: UIPRO_CODEX_SKILLS.map((name) => ({
        home: "agents" as const,
        path: `skills/${name}/SKILL.md`,
      })),
    },
  },
};

export const uiUxProMaxRecipe: RepoRecipe = {
  id: "ui-ux-pro-max-plugin-and-cli",
  label: "ui-ux-pro-max plugin and CLI",
  unit: "whole",
  trust: "repo",
  installer: UI_UX_PRO_MAX_INSTALLER,
  recognize: (tree) =>
    Effect.gen(function* () {
      const { remote } = tree;
      if (!remote) return miss("not a whole git repository");
      const { claude } = yield* readMarketplaces(tree);
      if (!claude?.plugins.some((plugin) => plugin.name === UI_UX_PRO_MAX)) {
        return miss("the Claude marketplace does not list ui-ux-pro-max");
      }
      const plugins = yield* pluginPointers(tree, remote, claude.name, { claude, codex: null });
      return {
        _tag: "Match",
        projection: {
          copies: [],
          writes: [
            ...plugins.writes,
            tileBundlePointer(
              UI_UX_PRO_MAX,
              "The ui-ux-pro-max skills, installed on Codex by the repository's uipro CLI.",
              ["codex"],
              remote.commit,
            ),
          ],
        },
      } satisfies Match;
    }),
};
